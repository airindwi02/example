/* eslint-disable @typescript-eslint/no-require-imports -- Node-only browser checks. */
const {chromium,expect}=require('@playwright/test');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.WORKER_BASE||'http://127.0.0.1:3000';
 await page.goto(base+'/daily-worker');
 await expect(page.getByRole('heading',{name:'Tugas Hari Ini'})).toBeVisible();
 await expect(page.locator('.w-stats')).toContainText('248');
 await page.getByRole('button',{name:'Keluar',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Yakin ingin keluar?'})).toBeVisible();
 await page.getByRole('button',{name:'Batal',exact:true}).click();
 await page.getByRole('navigation',{name:'Navigasi Daily Worker'}).getByRole('link',{name:'Penerimaan',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Catat Bahan Baku Masuk'})).toBeVisible();
 await page.getByRole('button',{name:'Simpan Penerimaan',exact:true}).click();
 await expect(page.locator('#receipt-error')).toBeVisible();
 await page.getByRole('combobox',{name:'Nama Bahan',exact:true}).selectOption('BHN-02');
 await page.getByLabel('Jumlah',{exact:true}).fill('-2');
 await page.getByLabel('Tanggal Penerimaan',{exact:true}).fill('31/02/2026');
 await page.getByRole('button',{name:'Simpan Penerimaan',exact:true}).click();
 await expect(page.getByLabel('Jumlah',{exact:true})).toHaveAttribute('aria-invalid','true');
 await expect(page.getByLabel('Tanggal Penerimaan',{exact:true})).toHaveAttribute('aria-invalid','true');
 await page.getByLabel('Jumlah',{exact:true}).fill('20');
 await page.getByLabel('Tanggal Penerimaan',{exact:true}).fill('22/10/2026');
 await expect(page.locator('.w-receipt-info')).toContainText('35 kg');
 await page.getByRole('button',{name:'Simpan Penerimaan',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Stok terbaru: 35 kg');
 await expect(page.getByRole('button',{name:'Simpan Penerimaan',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Simpan & Catat Lagi',exact:true}).click();
 await expect(page.getByLabel('Jumlah',{exact:true})).toHaveValue('');
 await page.getByRole('combobox',{name:'Nama Bahan',exact:true}).selectOption('BHN-02');
 await page.getByLabel('Jumlah',{exact:true}).fill('1,5');
 await page.getByRole('button',{name:'Simpan & Catat Lagi',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Stok terbaru: 36.5 kg');
 await page.getByRole('button',{name:'Batal',exact:true}).click();
 await expect(page.getByRole('status')).toHaveCount(0);
 await page.getByRole('navigation').getByRole('link',{name:'Dashboard',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Tugas Hari Ini'})).toBeVisible();
 await expect(page.locator('.w-stats>a').last()).toContainText('5');
 await page.evaluate(()=>document.fonts.ready);
 await page.locator('img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode().catch(()=>{}))));
 await page.screenshot({path:'.worker-qa/stage1-dashboard.png',fullPage:true,animations:'disabled'});
 fs.writeFileSync('.worker-qa/stage1-results.json',JSON.stringify({dashboard:true,logoutCancel:true,receivingValidation:true,stockAddition:true,duplicatePrevented:true,saveAgain:true,decimal:true,cancel:true,summary:true,errors},null,2));
 console.log('PASS dashboard, modal, receiving validation, 15→35→36.5 stock, save-again, cancel, summary; errors:',errors);
 await browser.close();if(errors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});